def translate_phrase_to_thai(phrase: str) -> str:
    cleaned = phrase.strip().lower()
    if not cleaned:
        return ""

    # Direct match in dictionary
    if cleaned in TERM_MAP:
        return TERM_MAP[cleaned]

    # Clean punctuation & parentheticals
    p_clean = re.sub(r"[\(\)\[\]]", "", cleaned).strip()
    if p_clean in TERM_MAP:
        return TERM_MAP[p_clean]

    # Handle patterns: "kind of X", "type of X", "species of X"
    m_kind = re.match(r"^(?:a\s+)?(?:kind|type|species|variety)\s+of\s+(.+)$", cleaned)
    if m_kind:
        target = m_kind.group(1).strip()
        tr = TERM_MAP.get(target) or target
        return f"ชนิดของ{tr}"

    # Handle "name of a X" / "name of X"
    m_name = re.match(r"^name\s+of\s+(?:a\s+)?(.+)$", cleaned)
    if m_name:
        target = m_name.group(1).strip()
        tr = TERM_MAP.get(target) or target
        return f"ชื่อ{tr}"

    # Handle "used in X"
    m_used = re.match(r"^used\s+in\s+(.+)$", cleaned)
    if m_used:
        target = m_used.group(1).strip()
        tr = TERM_MAP.get(target) or target
        return f"ใช้ใน{tr}"

    # Handle "X radical"
    m_rad = re.match(r"^(.+)\s+radical(?:\s+\(.*?\))?$", cleaned)
    if m_rad:
        target = m_rad.group(1).strip()
        tr = TERM_MAP.get(target) or target
        return f"หมวดอักษร {tr}"

    # Component-based translation for compound words: "or again", "on the other hand"
    tokens = [t.strip() for t in re.split(r"[,;/]+", cleaned) if t.strip()]
    if len(tokens) > 1:
        th_parts = []
        for t in tokens:
            th_t = translate_phrase_to_thai(t)
            if th_t and th_t not in th_parts:
                th_parts.append(th_t)
        if th_parts:
            return ", ".join(th_parts)

    # Word-by-word fallback if phrase contains 2-3 words
    words = cleaned.split()
    if 1 < len(words) <= 3:
        th_words = [TERM_MAP.get(w, w) for w in words]
        if any(w in TERM_MAP for w in words):
            return " ".join(th_words)

    # Fallback to Title-cased English if no translation available
    return phrase.strip().title()


def merge_and_enrich():
    print(f"Loading existing public kanji from: {PUBLIC_KANJI_PATH}")
    with open(PUBLIC_KANJI_PATH, "r", encoding="utf-8") as f:
        public_kanji = json.load(f)
    print(f"Current public kanji count: {len(public_kanji)}")

    print(f"Loading reference kanji dataset from: {REF_KANJI_PATH}")
    with open(REF_KANJI_PATH, "r", encoding="utf-8") as f:
        ref_kanji = json.load(f)
    print(f"Reference kanji count: {len(ref_kanji)}")

    merged = {}
    translated_count = 0
    preserved_count = 0

    # JLPT level mapping
    jlpt_map = {1: "N1", 2: "N2", 3: "N3", 4: "N4", 5: "N5"}

    for char, ref_entry in ref_kanji.items():
        if char in public_kanji:
            # Preserve existing high quality entry 100%
            merged[char] = public_kanji[char]
            preserved_count += 1
            continue

        # Build new entry from ref_entry
        strokes = ref_entry.get("strokes") or 0
        meanings = ref_entry.get("meanings") or []
        readings_on = ref_entry.get("readings_on") or []
        readings_kun = ref_entry.get("readings_kun") or []
        jlpt_num = ref_entry.get("jlpt_new")
        lvl = jlpt_map.get(jlpt_num)

        en_str = ", ".join(m.title() for m in meanings) if meanings else "-"

        # Translate meanings to Thai
        th_parts = []
        for m in meanings:
            th_trans = translate_phrase_to_thai(m)
            if th_trans and th_trans not in th_parts:
                th_parts.append(th_trans)

        th_str = ", ".join(th_parts) if th_parts else en_str

        merged[char] = {
            "on": readings_on,
            "kun": readings_kun,
            "en": en_str,
            "th": th_str,
            "strokes": strokes,
            "lvl": lvl or "N1"  # Default non-jouyou rare kanji to N1 level tier
        }
        translated_count += 1

    print(f"Total merged kanji: {len(merged)}")
    print(f"Preserved curated Joyo kanji: {preserved_count}")
    print(f"Enriched additional kanji: {translated_count}")

    # Write merged kanji database to public/data/kanji.json
    with open(PUBLIC_KANJI_PATH, "w", encoding="utf-8") as f:
        json.dump(merged, f, ensure_ascii=False, indent=2)
    print(f"Successfully saved updated {PUBLIC_KANJI_PATH}")

    # Synchronize reference index as well
    if os.path.exists(REF_INDEX_PATH):
        with open(REF_INDEX_PATH, "r", encoding="utf-8") as f:
            ref_idx = json.load(f)

        k_dict = ref_idx.get("kanji_dict", {})
        for char, entry in merged.items():
            if char in k_dict:
                k_dict[char]["meaning_th"] = entry["th"]
            else:
                k_dict[char] = {
                    "strokes": entry["strokes"],
                    "jlpt": entry.get("lvl"),
                    "meanings_en": [entry["en"]],
                    "meaning_th": entry["th"],
                    "readings_on": entry["on"],
                    "readings_kun": entry["kun"]
                }
        ref_idx["kanji_dict"] = k_dict
        ref_idx["total_kanji"] = len(k_dict)
        ref_idx["kanji_with_thai"] = sum(1 for v in k_dict.values() if v.get("meaning_th"))

        with open(REF_INDEX_PATH, "w", encoding="utf-8") as f:
            json.dump(ref_idx, f, ensure_ascii=False, indent=2)
        print(f"Synchronized {REF_INDEX_PATH} (Kanji with Thai: {ref_idx['kanji_with_thai']})")


if __name__ == "__main__":
    merge_and_enrich()
